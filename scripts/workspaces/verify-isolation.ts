import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { prisma } from '../../src/lib/prisma';
import { workspaceContext, withWorkspaceMaintenance } from '../../src/lib/workspaces/context';
import { beginWorkspaceDeletion, resumeWorkspaceDeletion } from '../../src/lib/workspaces/deletion';
import { withWorkspaceActivity } from '../../src/lib/workspaces/activity';
import { registerWorkspaceFile } from '../../src/lib/workspaces/files';
import { updateLora } from '../../src/lib/workspaces/loraAccess';
import { withWorkspaceRoute } from '../../src/lib/workspaces/route';
import { NextRequest, NextResponse } from 'next/server';

async function main() {
  assert.ok(process.env.ENGUI_DATABASE_URL?.includes('verification.db'), 'Use only the isolated verification database.');
  const original = await prisma.workspace.findFirstOrThrow({ where: { isProtected: true } });
  const galleryBefore = await prisma.galleryAsset.count({ where: { workspaceId: original.id } });
  const tag = 'scope-test-' + randomUUID();
  const a = await prisma.workspace.create({ data: { userId: original.userId, name: tag + '-A' } });
  const b = await prisma.workspace.create({ data: { userId: original.userId, name: tag + '-B' } });
  const scope = <T>(id: string, fn: () => Promise<T>) => workspaceContext.run({ kind: 'workspace', workspaceId: id, revision: 0 }, async () => await fn());
  const ap = await scope(a.id, () => prisma.videoProject.create({ data: { workspaceId: a.id, title: 'A project' } }));
  const bp = await scope(b.id, () => prisma.videoProject.create({ data: { workspaceId: b.id, title: 'B project' } }));
  assert.equal(await scope(b.id, () => prisma.videoProject.findUnique({ where: { id: ap.id } })), null);
  assert.equal((await scope(b.id, () => prisma.videoProject.findMany())).length, 1);
  await assert.rejects(() => scope(b.id, () => prisma.videoProject.update({ where: { id: ap.id }, data: { title: 'foreign' } })));
  await assert.rejects(() => scope(b.id, () => prisma.videoProject.deleteMany({ where: { id: { in: [ap.id, bp.id] } } })));
  await assert.rejects(() => scope(b.id, () => prisma.videoProject.create({ data: { workspaceId: a.id, title: 'foreign' } })));
  await assert.rejects(() => scope(b.id, () => prisma.videoTrack.create({ data: { projectId: ap.id, type: 'video', label: 'foreign' } })));
  const track = await scope(a.id, () => prisma.videoTrack.create({ data: { projectId: ap.id, type: 'video', label: 'A track' } }));
  await assert.rejects(() => scope(a.id, () => prisma.videoTrack.update({ where: { id: track.id }, data: { projectId: bp.id } })));
  const shared = await scope(original.id, () => prisma.loRA.create({ data: { workspaceId: original.id, name: tag, fileName: tag + '.safetensors', s3Path: '/runpod-volume/loras/' + tag + '.safetensors', s3Url: 'https://example.invalid/loras/' + tag, fileSize: BigInt(1), extension: '.safetensors' } }));
  assert.equal(await scope(a.id, () => prisma.loRA.findUnique({ where: { id: shared.id } })), null);
  await scope(original.id, () => updateLora(shared.id, { isShared: true }));
  assert.ok(await scope(a.id, () => prisma.loRA.findUnique({ where: { id: shared.id } })));
  await assert.rejects(() => scope(a.id, () => updateLora(shared.id, { baseModel: 'wan2.2' })));
  await assert.rejects(() => prisma.workspace.delete({ where: { id: original.id } }));
  await assert.rejects(() => prisma.workspace.update({ where: { id: original.id }, data: { isProtected: false } }));
  await assert.rejects(() => beginWorkspaceDeletion(original.id, original.name));

  const route = withWorkspaceRoute(async () => NextResponse.json(await prisma.videoProject.findMany()));
  assert.equal((await route(new NextRequest('http://localhost/api/test'))).status, 400);
  assert.equal((await route(new NextRequest('http://localhost/api/test?workspaceId=' + a.id, { headers: { 'x-workspace-id': b.id } }))).status, 403);
  const bodyMismatch = await route(new NextRequest('http://localhost/api/test', { method: 'POST', headers: { 'x-workspace-id': b.id, 'content-type': 'application/json' }, body: JSON.stringify({ workspaceId: a.id }) }));
  assert.equal(bodyMismatch.status, 403);
  const scopedRows = await (await route(new NextRequest('http://localhost/api/test', { headers: { 'x-workspace-id': b.id } }))).json();
  assert.deepEqual(scopedRows.map((r: any) => r.id), [bp.id]);

  const fileA = path.resolve('public/generations/' + tag + '-A.txt');
  const fileB = path.resolve('public/generations/' + tag + '-B.txt');
  await fs.mkdir(path.dirname(fileA), { recursive: true });
  await scope(a.id, () => registerWorkspaceFile(fileA));
  await scope(b.id, () => registerWorkspaceFile(fileB));
  await fs.writeFile(fileA, 'A'); await fs.writeFile(fileB, 'B');
  const legacyA = path.resolve('generations/' + path.basename(fileA));
  const scratchA = path.resolve('temp/' + tag + '.txt');
  await fs.mkdir(path.dirname(legacyA), { recursive: true }); await fs.mkdir(path.dirname(scratchA), { recursive: true });
  await fs.writeFile(legacyA, 'legacy A');
  await scope(a.id, () => registerWorkspaceFile(scratchA)); await fs.writeFile(scratchA, 'scratch A');
  await scope(a.id, () => prisma.job.create({ data: { workspaceId: a.id, userId: original.userId, type: 'image', modelId: 'z-image', status: 'processing', prompt: 'local cancellation fixture', runpodJobId: 'fixture-remote-id', endpointId: 'fixture-endpoint', options: '{}' } }));
  let providerTerminal = false;
  let cancels = 0;
  const originalFetch = globalThis.fetch;
  globalThis.fetch = (async (input: any, init: any) => {
    const url = String(input);
    assert.ok(url.startsWith('https://api.runpod.ai/v2/fixture-endpoint/'), 'Unexpected network attempt in deletion fixture.');
    if (url.includes('/cancel/')) { assert.equal(init.method, 'POST'); cancels++; return Response.json({ status: 'IN_PROGRESS' }); }
    return Response.json({ status: providerTerminal ? 'CANCELLED' : 'IN_PROGRESS' });
  }) as typeof fetch;
  let release!: () => void;
  let entered!: () => void;
  const ready = new Promise<void>(r => { entered = r; });
  const busy = withWorkspaceActivity(a.id, 'test-writer', async () => { entered(); await new Promise<void>(r => { release = r; }); });
  await ready;
  await beginWorkspaceDeletion(a.id, a.name);
  await assert.rejects(() => scope(a.id, () => prisma.videoProject.create({ data: { workspaceId: a.id, title: 'late write' } })));
  await resumeWorkspaceDeletion(a.id);
  assert.ok(await prisma.workspace.findUnique({ where: { id: a.id } }), 'Deletion must wait for the active writer.');
  assert.equal(await fs.readFile(fileA, 'utf8'), 'A');
  release(); await busy;
  await resumeWorkspaceDeletion(a.id);
  assert.equal(cancels, 1);
  assert.ok(await prisma.workspace.findUnique({ where: { id: a.id } }), 'A cancel acknowledgement is not terminal evidence.');
  providerTerminal = true;
  await resumeWorkspaceDeletion(a.id);
  globalThis.fetch = originalFetch;
  const deletion = await prisma.workspaceDeletion.findUniqueOrThrow({ where: { workspaceId: a.id } });
  assert.equal(deletion.status, 'completed', deletion.error || 'Deletion did not complete.');
  assert.equal(await prisma.workspace.findUnique({ where: { id: a.id } }), null);
  await assert.rejects(() => fs.stat(fileA));
  await assert.rejects(() => fs.stat(legacyA));
  await assert.rejects(() => fs.stat(scratchA));
  assert.equal(await fs.readFile(fileB, 'utf8'), 'B');
  assert.ok(await prisma.videoProject.findUnique({ where: { id: bp.id } }));
  assert.ok(await prisma.loRA.findUnique({ where: { id: shared.id } }));
  assert.equal(await prisma.galleryAsset.count({ where: { workspaceId: original.id } }), galleryBefore);
  await resumeWorkspaceDeletion(a.id);
  console.log(JSON.stringify({ passed: true, galleryPreserved: galleryBefore, scenarios: ['A/B reads', 'direct-ID writes', 'mixed bulk', 'inherited ownership', 'Default protection', 'shared sources', 'request mismatches', 'writer drain', 'provider cancellation confirmation', 'public/legacy/temp exact cleanup', 'deletion retry'] }, null, 2));
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => prisma.$disconnect());
